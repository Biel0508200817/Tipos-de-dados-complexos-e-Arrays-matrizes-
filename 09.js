/**
 * ### **9️⃣ Usando `concat`**

Crie dois arrays: `parte1 = [1, 2, 3]` e `parte2 = [4, 5, 6]`. Use `concat` para juntar os dois arrays e exiba o resultado.
 */
const parte1 = [1, 2, 3];
const parte2 = [4, 5, 6];
const combinado = parte1.concat(parte2);
console.log(combinado); // Saída: [1, 2, 3, 4, 5, 6]